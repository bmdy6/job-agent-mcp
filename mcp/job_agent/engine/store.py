"""Storage contract. SQLite implementation lives exclusively in store/."""
from typing import ContextManager, Protocol
from job_agent.engine.models import Job, Record, Status, Reason


class DeliveryStore(Protocol):
    dry_run: bool
    def exclusive(self) -> ContextManager[None]: ...
    def add(self, job: Job) -> bool: ...
    def prepare_run(self, config: dict, *, batch_token=None, greetings=None) -> None: ...
    def records(self) -> list[Record]: ...
    def update(self, job: Job, status: Status, reason: Reason,
               attempted_at: float | None = None, *, error_detail: str = '') -> None: ...
    def record_resume_selection(self, job: Job, selection: dict) -> None: ...
